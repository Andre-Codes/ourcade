/* ============================================================
   GEN-DUNGEON-EFFECT-WORDS — bulk word→category lists for Dictionary Dungeon,
   written to src/data/generated/dungeon-effect-words.js.

   WHY: effects.js hand-curates a word list per effect category. `food` grew to
   ~250 words and it shows — food words land constantly and the heal actually
   feels like part of the game. Every other category sat at ~35–50 words, so a
   typed word usually matched nothing and read as "no special weight". This
   script fattens the three categories that have a real-world list backing them:

       animals + birds        → beastly
       food & drink           → food
       trees                  → nature

   Source files live in the repo ROOT (they're raw reference lists, not curated
   game data). They are NOT clean: they carry concatenated multi-word names
   ("acornwoodpecker"), Latin genus names ("adansonia"), and spaced entries. So
   every candidate is filtered against the SAME dictionary the game plays with
   (dict.js allWords(), baked by gen-dungeon-dict.js) — if the player can't type
   it, it doesn't ship.

   We deliberately DON'T subtract the hand-curated words here: effects.js
   concatenates hand lists ahead of the generated ones and its lookup map is
   first-assignment-wins, so a curated entry always beats a generated one and
   the overlap costs a few KB at most. Keeping the generator ignorant of
   effects.js also avoids a circular import (effects.js imports what we write).

   Skipped on purpose: vehicles, sports, countries, world capitals. They're real
   words but nothing in a dungeon reads as AEROBICS or BELGIUM, and forcing them
   into a category would make the semantic system noise.

   Run:  npm run gen:dungeon-effect-words     (no network, no API key)
   ============================================================ */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { allWords } from "../src/games/dictionary-dungeon/dict.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "src", "data", "generated");
const OUT_FILE = "dungeon-effect-words.js";

// source file (repo root) → effect category in effects.js
const SOURCES = [
  { file: "animals_one_word_only.txt", category: "beastly" },
  { file: "birds_one_word_only.txt", category: "beastly" },
  { file: "food_and_drink_one_word_only.txt", category: "food" },
  { file: "trees_one_word_only.txt", category: "nature" },
];

function loadCandidates(file) {
  const full = path.join(ROOT, file);
  if (!fs.existsSync(full)) {
    throw new Error(`gen-dungeon-effect-words: missing source list ${file}`);
  }
  return fs
    .readFileSync(full, "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim().toUpperCase())
    // Some lists are "key: value" (world capitals); take the key side only.
    .map((line) => line.split(":")[0].trim())
    .filter(Boolean);
}

// ── build ────────────────────────────────────────────────────────────────────
const dict = new Set(allWords());

// Category order matters: a word claimed by an earlier category keeps it, so a
// word in both the food and tree lists (ALMOND) stays food. This mirrors how
// effects.js resolves cross-category collisions by source order.
const claimed = new Set();
const byCategory = new Map();
const stats = [];

for (const { file, category } of SOURCES) {
  const raw = loadCandidates(file);
  const kept = [];
  for (const w of raw) {
    if (!/^[A-Z]+$/.test(w)) continue; // drops spaced/hyphenated entries
    if (!dict.has(w)) continue; // drops non-playable words
    if (claimed.has(w)) continue; // already owned by an earlier list
    claimed.add(w);
    kept.push(w);
  }
  kept.sort();
  if (!byCategory.has(category)) byCategory.set(category, []);
  byCategory.get(category).push(...kept);
  stats.push({ file, category, raw: raw.length, kept: kept.length });
}

const banner =
  "// AUTO-GENERATED by scripts/gen-dungeon-effect-words.js — do not edit by hand.\n" +
  "// Bulk word→category lists for Dictionary Dungeon's semantic effect system,\n" +
  "// filtered against the game's own dictionary so every word here is playable.\n" +
  "// effects.js merges these AFTER its hand-curated lists (curated wins ties).\n" +
  "// Run `npm run gen:dungeon-effect-words` to regenerate.\n";

const entries = [...byCategory.entries()]
  .map(([cat, words]) => `  ${cat}: ${JSON.stringify(words.sort())},`)
  .join("\n");

const body = `${banner}export const BULK_WORD_LISTS = {\n${entries}\n};\n`;

if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, OUT_FILE), body);

const total = [...byCategory.values()].reduce((a, w) => a + w.length, 0);
for (const s of stats) {
  console.log(
    `  ${s.file.padEnd(38)} ${String(s.raw).padStart(4)} raw → ${String(s.kept).padStart(4)} playable  (${s.category})`
  );
}
console.log(
  `gen-dungeon-effect-words: ${total} words across ${byCategory.size} categories → ` +
    `src/data/generated/${OUT_FILE} (${(Buffer.byteLength(body) / 1024).toFixed(1)} KB)`
);
